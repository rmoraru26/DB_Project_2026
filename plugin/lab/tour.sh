#!/usr/bin/env bash
# The plugin-only tour: campus_audit and the skeleton plugin in a MariaDB
# server that holds nothing else (no booking application, no project schema).
#
# Runs INSIDE the throw-away container started by scripts/plugin_lab.sh
# (make plugin-lab, or .\frantastic.cmd plugin-lab on Windows).  Each step
# prints the SQL it runs and what the server and the plugin answered, then
# checks that answer.  Exit status 0 when every check passed, so the same
# script is the clean-checkout test of this path in CI.
#
# Credentials: the root password reaches this container as
# MARIADB_ROOT_PASSWORD (generated by the host script, never printed).  It is
# written to /root/.my.cnf (mode 0600) inside the container, so that
# `docker exec -it campus-audit-plugin-lab mariadb` opens a root shell
# afterwards.  The container publishes no port.
set -u

LOG=/var/log/campus_audit/campus_audit.jsonl
PASS=0
FAIL=0

pass() { PASS=$((PASS + 1)); echo "   PASS: $1"; }
fail() { FAIL=$((FAIL + 1)); echo "   FAIL: $1"; [ $# -gt 1 ] && echo "         $2"; }
step() { echo; echo "== $1"; }
q() {      # q "<SQL>": run as root, show the statement and the result table
    printf '   SQL> %s\n' "$1"
    mariadb --table -e "$1" 2>&1 | quiet
}
quiet() {  # drop the client's framing of a failed statement, indent the rest
    grep -v -e '^--------------$' -e '^$' | sed 's/^/   /'
}
val() {    # val "<SQL>": one value, no decoration
    mariadb --batch --skip-column-names -e "$1" 2>&1 | tr -d '\r'
}
status() { val "SELECT VARIABLE_VALUE FROM information_schema.GLOBAL_STATUS WHERE VARIABLE_NAME = '$1';"; }
expect() { # expect "<description>" "<actual>" "<expected>"
    if [ "$2" = "$3" ]; then pass "$1"; else fail "$1" "expected '$3', got '$2'"; fi
}
mark() { wc -l < "$LOG" 2>/dev/null || echo 0; }
since() {  # since <line count>: the records written after that point
    tail -n +"$(( $1 + 1 ))" "$LOG"
}
show_records() {   # show_records <line count>: print the new records, one per line
    echo "   records written by the plugin:"
    since "$1" | grep -v "^$" | sed "s/^/   | /"
}
has() {    # has <line count> <description> <pattern> [<pattern>...]: a new record matches every pattern
    local from=$1 what=$2; shift 2
    local lines; lines=$(since "$from")
    local p
    for p in "$@"; do lines=$(printf '%s\n' "$lines" | grep -F -- "$p"); done
    if [ -n "$lines" ]; then pass "$what"; else fail "$what" "no new record contains: $*"; fi
}
random_hex() { head -c 12 /dev/urandom | od -An -tx1 | tr -d ' \n'; }

# ---------------------------------------------------------------- 0. the server
step "0. Waiting for the throw-away MariaDB server"
: "${MARIADB_ROOT_PASSWORD:?the host script passes MARIADB_ROOT_PASSWORD}"
umask 077
printf '[client]\nuser=root\npassword=%s\n' "$MARIADB_ROOT_PASSWORD" > /root/.my.cnf
# During initialisation the image runs a temporary server without networking;
# a TCP login succeeds only once the final server is up.
ready=0
for _ in $(seq 1 120); do
    if mariadb -h127.0.0.1 --protocol=tcp -e 'SELECT 1' >/dev/null 2>&1; then ready=1; break; fi
    sleep 1
done
if [ "$ready" != 1 ]; then echo "FAIL: the server did not become ready"; exit 1; fi
q "SELECT VERSION() AS server, @@plugin_dir AS plugin_dir, @@plugin_maturity AS plugin_maturity;"
echo "   plugin libraries in plugin_dir:"
ls -l "$(val 'SELECT @@plugin_dir;')" | grep -e campus_audit -e skeleton_audit | sed 's/^/   /'

# ---------------------------------------------------------------- 1. install
step "1. INSTALL SONAME: the server opens the library, checks its maturity and calls init"
q "INSTALL SONAME 'campus_audit';"
q "SELECT PLUGIN_NAME, PLUGIN_STATUS, PLUGIN_TYPE, PLUGIN_LIBRARY, PLUGIN_AUTH_VERSION, PLUGIN_MATURITY
     FROM information_schema.PLUGINS WHERE PLUGIN_NAME = 'campus_audit';"
expect "campus_audit is an ACTIVE AUDIT plugin" \
    "$(val "SELECT CONCAT(PLUGIN_STATUS, ' ', PLUGIN_TYPE) FROM information_schema.PLUGINS WHERE PLUGIN_NAME = 'campus_audit';")" "ACTIVE AUDIT"
expect "it declares 9 system variables" "$(val "SELECT COUNT(*) FROM information_schema.GLOBAL_VARIABLES WHERE VARIABLE_NAME LIKE 'CAMPUS\_AUDIT\_%';")" 9
expect "it declares 11 status variables" "$(val "SELECT COUNT(*) FROM information_schema.GLOBAL_STATUS WHERE VARIABLE_NAME LIKE 'CAMPUS\_AUDIT\_%';")" 11
expect "Campus_audit_state is ACTIVE" "$(status CAMPUS_AUDIT_STATE)" ACTIVE
has 0 "the log starts with a plugin_start record" '"event":"plugin_start"'

# ---------------------------------------------------------------- 2. watch a schema
step "2. Configure it at run time: watch the schema lab (SET GLOBAL, validated by a check function)"
m=$(mark)
q "CREATE DATABASE lab;
   CREATE TABLE lab.notes (id INT PRIMARY KEY, label VARCHAR(40), quantity INT CHECK (quantity > 0));
   SET GLOBAL campus_audit_databases = 'lab';
   SHOW GLOBAL VARIABLES LIKE 'campus\_audit\_databases';"
has "$m" "the change is recorded as config_change" '"event":"config_change"' '"variable":"campus_audit_databases"' '"value":"lab"'

# ---------------------------------------------------------------- 3. statements
step "3. Two INSERTs: one succeeds, one violates the CHECK constraint"
m=$(mark)
q "INSERT INTO lab.notes VALUES (1, 'secret label', 5);"
q "INSERT INTO lab.notes VALUES (2, 'invalid', 0);"
show_records "$m"
has "$m" "the successful INSERT: a table_write record" '"event":"table_write"' '"db":"lab"' '"table":"notes"'
has "$m" "... and a statement record with error_code 0" '"event":"statement"' '"error_code":0,' '"status":"ok"'
has "$m" "the rejected INSERT is recorded with its outcome (4025)" '"event":"statement"' '"error_code":4025'
has "$m" "the digest replaces every literal by ?" '"sql_digest":"INSERT INTO lab.notes VALUES (?, ?, ?)"'
if since "$m" | grep -q 'secret label'; then fail "no literal reaches the log" "found 'secret label'"; else pass "no literal reaches the log"; fi

# ---------------------------------------------------------------- 4. refusals
step "4. A statement the privilege system refuses, and a failed login"
READER_PW="r$(random_hex)"
# Through stdin, so the password is on no command line.
printf "CREATE USER lab_reader@localhost IDENTIFIED BY '%s';\nGRANT SELECT ON lab.* TO lab_reader@localhost;\n" "$READER_PW" | mariadb
m=$(mark)
# The privilege check runs before any table is opened, so the refusal raises
# no TABLE event, and a GENERAL event names no table: the plugin attributes
# the refusal to the session's default schema (here lab, which is watched).
echo "   The refusal raises no TABLE event; the plugin attributes it by the session's default schema (lab)."
printf '   SQL (as lab_reader, default schema lab)> DELETE FROM notes;\n'
MYSQL_PWD="$READER_PW" mariadb --no-defaults -ulab_reader -Dlab -e "DELETE FROM notes;" 2>&1 | quiet
printf '   login as lab_reader with a wrong password:\n'
MYSQL_PWD="wrong-$(random_hex)" mariadb --no-defaults -ulab_reader -e "SELECT 1;" 2>&1 | quiet
show_records "$m"
has "$m" "the refused DELETE is recorded (access_denied, 1142)" '"event":"statement"' '"error_code":1142' '"access_denied":true'
has "$m" "the failed login is recorded (connect_failed, 1045)" '"event":"connect_failed"' '"user":"lab_reader"' '"status":1045'

# ---------------------------------------------------------------- 5. validation
step "5. Invalid values are refused by the plugin's check functions, with the reason in SHOW WARNINGS"
refuse() {   # refuse "<SET statement>" "<expected part of the warning>" "<description>"
    local out
    printf '   SQL> %s SHOW WARNINGS;\n' "$1"
    out=$(printf '%s\nSHOW WARNINGS;\n' "$1" | mariadb --batch --skip-column-names --force 2>&1)
    printf '%s\n' "$out" | grep -v '^--------------$' | grep -v '^$' | sed 's/^/   /'
    if printf '%s' "$out" | grep -q 'ERROR 1231' && printf '%s' "$out" | grep -qF "$2"; then pass "$3"
    else fail "$3" "expected ER 1231 and '$2'"; fi
}
refuse "SET GLOBAL campus_audit_databases = 'bad name!';" "unsupported character in database name" \
    "a schema name with a space is refused"
refuse "SET GLOBAL campus_audit_file_path = '/etc/passwd';" "must end in .jsonl" \
    "a foreign file is refused as audit log (it would be appended to)"
expect "the previous values stay in force" \
    "$(val 'SELECT CONCAT(@@GLOBAL.campus_audit_databases, " ", @@GLOBAL.campus_audit_file_path);')" "lab $LOG"

# ---------------------------------------------------------------- 6. fail-open
step "6. Fail-open: the log cannot be written (/dev/full), the statement still succeeds, the loss is announced"
m=$(mark)
q "SET GLOBAL campus_audit_file_path = '/dev/full';"
echo "   the log it left records where logging went (handover, since 1.2.5):"
since "$m" | grep -F '"campus_audit_file_path"' | sed 's/^/   | /'
has "$m" "the redirect is recorded in the log it left" '"event":"config_change"' '"value":"/dev/full (previous: '
q "INSERT INTO lab.notes VALUES (3, 'during the outage', 1);"
expect "the INSERT succeeded" "$(val 'SELECT COUNT(*) FROM lab.notes WHERE id = 3;')" 1
expect "Campus_audit_state is DEGRADED" "$(status CAMPUS_AUDIT_STATE)" DEGRADED
q "SHOW GLOBAL STATUS WHERE Variable_name IN ('Campus_audit_state', 'Campus_audit_write_failures', 'Campus_audit_events_dropped', 'Campus_audit_last_error');"
m=$(mark)
q "SET GLOBAL campus_audit_file_path = '$LOG';"
expect "switching back makes it ACTIVE again" "$(status CAMPUS_AUDIT_STATE)" ACTIVE
show_records "$m"
has "$m" "an audit_gap record announces the lost records" '"event":"audit_gap"' '"dropped_events":'

# ---------------------------------------------------------------- 7. skeleton
step "7. The skeleton plugin (examples/skeleton_plugin): the same API in about 50 lines of code"
echo "   The same source built with -DSKELETON_EXPERIMENTAL declares maturity Experimental; this server accepts Beta and above:"
out=$(mariadb -e "INSTALL SONAME 'skeleton_audit_exp';" 2>&1)
printf '   SQL> INSTALL SONAME '"'"'skeleton_audit_exp'"'"';\n'
printf '%s\n' "$out" | grep ERROR | sed 's/^/   /'
if printf '%s' "$out" | grep -q 'ERROR 1126' && printf '%s' "$out" | grep -q 'experimental plugin'; then
    pass "the server refuses a plugin below plugin_maturity (ER 1126) before init runs"
else fail "the server refuses a plugin below plugin_maturity (ER 1126) before init runs" "got: $out"; fi
q "INSTALL SONAME 'skeleton_audit';"
q "SELECT PLUGIN_NAME, PLUGIN_STATUS, PLUGIN_TYPE, PLUGIN_LIBRARY FROM information_schema.PLUGINS WHERE PLUGIN_TYPE = 'AUDIT';"
before=$(val "SELECT VARIABLE_VALUE FROM information_schema.GLOBAL_STATUS WHERE VARIABLE_NAME = 'SKELETON_AUDIT_TABLE_EVENTS';")
q "SELECT COUNT(*) FROM lab.notes;"
after=$(val "SELECT VARIABLE_VALUE FROM information_schema.GLOBAL_STATUS WHERE VARIABLE_NAME = 'SKELETON_AUDIT_TABLE_EVENTS';")
q "SHOW GLOBAL STATUS LIKE 'skeleton\_audit\_%';"
expect "two audit plugins are ACTIVE at the same time" "$(val "SELECT COUNT(*) FROM information_schema.PLUGINS WHERE PLUGIN_TYPE = 'AUDIT' AND PLUGIN_STATUS = 'ACTIVE';")" 2
if [ "${after:-0}" -gt "${before:-0}" ] 2>/dev/null; then pass "the SELECT raised a TABLE event the skeleton counted ($before -> $after)"
else fail "the SELECT raised a TABLE event the skeleton counted" "$before -> $after"; fi
q "UNINSTALL SONAME 'skeleton_audit';"
expect "UNINSTALL removed it" "$(val "SELECT COUNT(*) FROM information_schema.PLUGINS WHERE PLUGIN_NAME = 'skeleton_audit';")" 0

# ---------------------------------------------------------------- summary
mariadb -e "DROP USER IF EXISTS lab_reader@localhost;"
echo
echo "== Result: $PASS passed, $FAIL failed"
cat <<'EOF'

Keep experimenting in this server (it holds nothing but these two plugins):
   docker exec -it campus-audit-plugin-lab mariadb                     root SQL shell
   docker exec campus-audit-plugin-lab tail -f /var/log/campus_audit/campus_audit.jsonl
Change examples/skeleton_plugin/skeleton_audit.cpp and run the lab again: the image rebuilds only what changed.
Remove the container: make plugin-lab-down   (Windows: .\frantastic.cmd plugin-lab-down)
EOF
[ "$FAIL" -eq 0 ]
